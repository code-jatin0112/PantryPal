export const retryDeletion = async (req, res, next) => {
  try {
    const { email, password } = req.body;
    const userId = req.user?.id;
    const result = await retryAccountDeletion({
      email,
      password,
      userId,
    });

    return res.status(200).json({
      success: true,
      data: result,
    });
  } catch (error) {
    next(error);
  }
};

